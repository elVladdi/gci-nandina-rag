"""Prospective, dynamically bound evaluator for the 0B-05C correction.

The historical EV-03/EV-04 runners retain their fixed historical hashes and
cannot legitimately consume a derived corpus.  This implementation therefore
imports their versioned helper semantics while validating dynamic corrective
corpus/index identities produced by the same authorized execution.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

from ..bm25_index import read_jsonl, sha256_file
from ..evaluation.metrics import acc_at_k, mrr_from_rank, rank_of_true
from ..retrieval.bm25 import load_bm25_index, retrieve
from . import evaluate_normative_bm25_flat_data_aduanas_v02 as flat
from . import evaluate_normative_bm25_hierarchical_data_aduanas_v02 as hierarchical
from .run_d1a_corrective_0b05c_v01 import ContractViolation, require


ROOT = Path(__file__).resolve().parents[2]
EVALSET = Path("data/processed/data_aduanas_evalset_clase87_v0.2.csv")
CONFIG = Path("src/configs/experiment_config.json")


def _relative(path: Path, root: Path = ROOT) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError as exc:
        raise ContractViolation(f"Corrective evaluator path escapes repository: {path}") from exc


def _read_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def _write_json_new(path: Path, payload: Mapping[str, Any]) -> None:
    require(not path.exists(), f"Corrective evaluator refuses overwrite or resume: {_relative(path)}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")


def _write_csv_new(path: Path, rows: Sequence[Mapping[str, Any]], fields: Sequence[str]) -> None:
    require(not path.exists(), f"Corrective evaluator refuses overwrite or resume: {_relative(path)}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8", newline="",) as handle:
        writer = csv.DictWriter(handle, fieldnames=list(fields), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def _normalize_rows(rows: Iterable[Mapping[str, Any]]) -> list[dict[str, str]]:
    return [{str(key): "" if value is None else str(value) for key, value in row.items()} for row in rows]


def validate_dynamic_inputs(arm: str, corpus_path: Path, index_path: Path, metadata_path: Path, *, config_path: Path = CONFIG) -> dict[str, Any]:
    """Validate only identities produced at future execution time.

    No historic fixed corpus/index hash is read here.  The derived corpus SHA is
    bound to the index metadata generated by the corresponding corrective
    builder, and the frozen k1/b policy remains fail-closed.
    """

    require(arm in {"EV03", "EV04"}, f"Unsupported corrective arm: {arm}")
    for path in (corpus_path, index_path, metadata_path, config_path):
        require(path.is_file(), f"Corrective evaluator input is missing: {_relative(path)}")
    metadata = _read_json(metadata_path)
    corpus_sha = sha256_file(corpus_path)
    index_sha = sha256_file(index_path)
    require(metadata.get("arm") == arm, "Corrective index metadata arm does not match evaluator arm")
    require(metadata.get("input", {}).get("corpus_sha256") == corpus_sha, "Corrective index metadata corpus SHA does not match derived corpus")
    require(metadata.get("output", {}).get("bm25_index_sha256") == index_sha, "Corrective index metadata index SHA does not match derived index")
    params = metadata.get("bm25_params", {})
    require((float(params.get("k1", 0)), float(params.get("b", 0))) == (1.5, 0.75), "Corrective evaluator rejects a change to frozen BM25 k1/b")
    config = _read_json(config_path)
    bm25 = config.get("bm25", {})
    require((float(bm25.get("k1", 0)), float(bm25.get("b", 0))) == (1.5, 0.75), "Current config violates frozen BM25 k1/b")
    index = load_bm25_index(index_path)
    require((float(index.k1), float(index.b)) == (1.5, 0.75), "Loaded corrective index violates frozen BM25 k1/b")
    return {"corpus_sha256": corpus_sha, "index_sha256": index_sha, "index_metadata_sha256": sha256_file(metadata_path), "config_sha256": sha256_file(config_path), "metadata": metadata, "index": index}


def materialize_corrective_corpus(source: Path, destination: Path, patches: Sequence[Mapping[str, Any]], *, root: Path = ROOT) -> str:
    """Apply the frozen two-record patch without rewriting unpatched JSONL bytes."""

    require(source.is_file(), f"Frozen corrective source is missing: {_relative(source, root)}")
    require(not destination.exists(), f"Corrective corpus refuses overwrite or resume: {_relative(destination, root)}")
    patch_by_code = {str(item["code"]): item for item in patches}
    require(len(patch_by_code) == 2, "Corrective corpus patch contract must contain exactly two codes")
    changed: set[str] = set()
    lines: list[bytes] = []
    for raw in source.read_bytes().splitlines():
        payload = json.loads(raw)
        code = str(payload.get("codigo", "")).strip()
        patch = patch_by_code.get(code)
        if patch is None:
            lines.append(raw)
            continue
        expected = str(patch["match"]["original_jsonl_line_sha256"])
        require(hashlib.sha256(raw).hexdigest() == expected, f"Corrective patch source identity drifted for {code}")
        for key, value in dict(patch["replacement"]).items():
            payload[key] = value
        lines.append(json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))
        changed.add(code)
    require(changed == set(patch_by_code), "Corrective corpus did not match exactly the frozen two-code patch scope")
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("xb") as handle:
        handle.write(b"\n".join(lines) + b"\n")
    return sha256_file(destination)


def _flat_rows(evalset: Path, corpus_path: Path, index: Any, depth: int) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    eval_rows = flat._read_csv(evalset)
    flat._validate_eval_rows(eval_rows)
    corpus_by_code, _ = flat._load_corpus_map(read_jsonl(corpus_path))
    cases: list[dict[str, Any]] = []
    candidates: list[dict[str, Any]] = []
    for row in eval_rows:
        hits = retrieve(index, flat._clean(row.get(flat.QUERY_COLUMN)), top_n=depth)
        cases.append(flat._build_case_row(row, hits, corpus_by_code))
        candidates.extend(flat._candidate_rows(row, hits, corpus_by_code))
    return cases, candidates, flat._metrics(cases)


def _hierarchical_rows(evalset: Path, corpus_path: Path, index: Any, depth: int) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    """Reuse the frozen hierarchical query, collapse, rank, and metric helpers."""

    eval_rows = hierarchical.read_csv(evalset)
    hierarchical.validate_eval(eval_rows)
    corpus_by_code: dict[str, Mapping[str, Any]] = {}
    for row in read_jsonl(corpus_path):
        code = hierarchical.code8(row.get("codigo"))
        if code and str(row.get("tipo", "")) == "nandina_8":
            require(code not in corpus_by_code, f"Corrective EV04 corpus has duplicate NANDINA-8 code: {code}")
            corpus_by_code[code] = row
    cases: list[dict[str, Any]] = []
    candidates: list[dict[str, Any]] = []
    for eval_row in eval_rows:
        query = hierarchical.clean(eval_row.get(hierarchical.QUERY_COLUMN))
        expected = hierarchical.code8(eval_row.get(hierarchical.LABEL_COLUMN))
        raw_hits = retrieve(index, query, top_n=len(index.doc_ids))
        hits, collapse = hierarchical.collapse_hits(raw_hits, depth)
        rank = rank_of_true(hits, expected)
        top = hits[0] if hits else {}
        row: dict[str, Any] = {
            "case_id": hierarchical.clean(eval_row.get("case_id")), "id_unico": hierarchical.clean(eval_row.get("id_unico")),
            "declaracion": hierarchical.clean(eval_row.get("DECLARACION")), "serie": hierarchical.clean(eval_row.get("SERIE")),
            "query": query, "nandina_ref": expected, "rank_ref": rank, "retrieved_count": len(hits),
            "raw_retrieved_count": collapse["raw_retrieved_count"], "raw_repeated_code_count": collapse["raw_repeated_code_count"],
            "effective_ranking_has_repeated_codes": int(collapse["effective_has_repeated_codes"]), "top1_code": hierarchical.clean(top.get("code")),
            "top1_score": top.get("score", "") if top else "", "reciprocal_rank": mrr_from_rank(rank), "method": hierarchical.METHOD,
        }
        for k in hierarchical.K_VALUES:
            row[f"hit_top_{k}"] = int(acc_at_k(rank, k))
        for k in hierarchical.RECALL_K_VALUES:
            row[f"hit_recall_{k}"] = int(acc_at_k(rank, k))
        for k in hierarchical.HIERARCHICAL_K_VALUES:
            row[f"exact_at_{k}"] = int(acc_at_k(rank, k))
            row[f"hs6_at_{k}"] = hierarchical.family_hit(hits, expected, 6, k)
            row[f"hs4_at_{k}"] = hierarchical.family_hit(hits, expected, 4, k)
            row[f"chapter_at_{k}"] = hierarchical.family_hit(hits, expected, 2, k)
        cases.append(row)
        for hit in hits:
            code = hierarchical.clean(hit.get("code"))
            candidates.append({"case_id": row["case_id"], "id_unico": row["id_unico"], "nandina_ref": expected, "candidate_rank": int(hit["rank"]), "candidate_raw_rank": int(hit.get("raw_rank", hit["rank"])), "candidate_code": code, "candidate_doc_id": hierarchical.clean(corpus_by_code.get(code, {}).get("doc_id")), "score": float(hit["score"]), "is_reference_code": int(code == expected), "method": hierarchical.METHOD})
    return cases, candidates, hierarchical.metrics_from_cases(cases)


def evaluate_arm(arm: str, corpus_path: Path, index_path: Path, metadata_path: Path, output_dir: Path, *, evalset: Path = EVALSET, config_path: Path = CONFIG, root: Path = ROOT) -> dict[str, Any]:
    """Produce future case/aggregate results after the runner has authorized it."""

    require(not output_dir.exists(), f"Corrective evaluator refuses overwrite or resume: {_relative(output_dir, root)}")
    inputs = validate_dynamic_inputs(arm, corpus_path, index_path, metadata_path, config_path=config_path)
    evalset = (root / evalset).resolve() if not evalset.is_absolute() else evalset.resolve()
    require(evalset.is_file(), f"Frozen EVAL is missing: {_relative(evalset, root)}")
    depth = 100 if arm == "EV03" else 200
    if arm == "EV03":
        cases, candidates, metrics = _flat_rows(evalset, corpus_path, inputs["index"], depth)
        prefix = "normative_flat"
    else:
        cases, candidates, metrics = _hierarchical_rows(evalset, corpus_path, inputs["index"], depth)
        prefix = "normative_hierarchical"
    output_dir.mkdir(parents=True, exist_ok=False)
    ranking = output_dir / f"{prefix}_results.csv"
    summary = output_dir / f"{prefix}_case_summary.csv"
    metric_file = output_dir / f"{prefix}_metrics.json"
    _write_csv_new(ranking, _normalize_rows(candidates), sorted({key for row in candidates for key in row}))
    _write_csv_new(summary, _normalize_rows(cases), sorted({key for row in cases for key in row}))
    payload = {"arm": arm, "dynamic_inputs": {key: value for key, value in inputs.items() if key not in {"metadata", "index"}}, "evalset": _relative(evalset, root), "evalset_sha256": sha256_file(evalset), "retrieval_depth": depth, "metrics": metrics, "outputs": {"ranking": _relative(ranking, root), "case_summary": _relative(summary, root)}}
    _write_json_new(metric_file, payload)
    return payload


def compare_control_reproduction(expected_ranking: Path, actual_ranking: Path, expected_summary: Path, actual_summary: Path, expected_metrics: Mapping[str, Any], actual_metrics: Mapping[str, Any]) -> dict[str, Any]:
    """Require exact effective ranking, case summary, and metric evidence.

    Runtime/platform/timestamp metadata are intentionally outside this strict
    comparison; all ranking, case-level, numerator, denominator, and value
    evidence remains in scope.
    """

    expected_rank = flat._read_csv(expected_ranking)
    actual_rank = flat._read_csv(actual_ranking)
    expected_cases = flat._read_csv(expected_summary)
    actual_cases = flat._read_csv(actual_summary)
    metrics_equal = expected_metrics == actual_metrics
    result = {"ranking_exact": expected_rank == actual_rank, "case_summary_exact": expected_cases == actual_cases, "metrics_exact": metrics_equal, "comparison_scope": "EFFECTIVE_FULL_RANKING_CASE_LEVEL_AND_METRICS_EXCLUDING_RUNTIME_TIMESTAMPS"}
    require(all(result[key] for key in ("ranking_exact", "case_summary_exact", "metrics_exact")), "Mandatory control reproduction is not exact")
    return {**result, "status": "PASS"}


def reproduce_ev04_decision885_control(
    corpus_path: Path,
    index_path: Path,
    metadata_path: Path,
    output_dir: Path,
    *,
    frozen_ranking: Path,
    frozen_case_summary: Path,
    frozen_metrics: Mapping[str, Any],
    root: Path = ROOT,
) -> dict[str, Any]:
    """Run and cryptographically compare the mandatory EV04 Decision885 control.

    The caller must invoke this before materializing either corrected corpus.
    A mismatch raises ``ContractViolation`` through ``compare_control_reproduction``
    and therefore cannot be ignored by a later corrected-arm invocation.
    """

    result = evaluate_arm("EV04", corpus_path, index_path, metadata_path, output_dir, root=root)
    return compare_control_reproduction(
        frozen_ranking,
        output_dir / "normative_hierarchical_results.csv",
        frozen_case_summary,
        output_dir / "normative_hierarchical_case_summary.csv",
        frozen_metrics,
        result["metrics"],
    )


def produce_case_level_comparison(original: Sequence[Mapping[str, Any]], corrective: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    original_by_case = {str(row["case_id"]): dict(row) for row in original}
    corrective_by_case = {str(row["case_id"]): dict(row) for row in corrective}
    require(set(original_by_case) == set(corrective_by_case), "Case-level comparison requires identical frozen case IDs")
    return [{"case_id": case_id, "original": original_by_case[case_id], "corrective": corrective_by_case[case_id]} for case_id in sorted(original_by_case)]


def produce_aggregate_comparison(original_metrics: Mapping[str, Any], corrective_metrics: Mapping[str, Any]) -> dict[str, Any]:
    names = [row["metric"] for row in original_metrics.get("metric_table", [])]
    return {name: {"original": original_metrics[name], "corrective": corrective_metrics[name], "delta": float(corrective_metrics[name]) - float(original_metrics[name])} for name in names}


def produce_unified_sensitivity_summary(ev03: Mapping[str, Any], ev04: Mapping[str, Any]) -> dict[str, Any]:
    return {"artifact_id": "0b05c_unified_corrective_sensitivity_summary_v0.1", "ev03": dict(ev03), "ev04": dict(ev04), "interpretation_status": "PENDING_AUTHORIZED_EXECUTION"}


def write_execution_manifest(path: Path, payload: Mapping[str, Any]) -> None:
    _write_json_new(path, payload)


def write_hash_ledger(path: Path, files: Sequence[Path], *, root: Path = ROOT) -> None:
    require(path not in files, "Future hash ledger must exclude only itself")
    _write_json_new(path, {"artifact_id": "0b05c_corrective_execution_hash_ledger_v0.1", "files": [{"path": _relative(item, root), "sha256": sha256_file(item)} for item in files]})


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Evaluate an authorized 0B-05C corrective BM25 arm.")
    parser.add_argument("--arm", choices=["EV03", "EV04"], required=True)
    parser.add_argument("--corpus", type=Path, required=True)
    parser.add_argument("--index", type=Path, required=True)
    parser.add_argument("--index-metadata", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--evalset", type=Path, default=EVALSET)
    parser.add_argument("--config", type=Path, default=CONFIG)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    payload = evaluate_arm(args.arm, args.corpus, args.index, args.index_metadata, args.output_dir, evalset=args.evalset, config_path=args.config)
    print(json.dumps(payload, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
