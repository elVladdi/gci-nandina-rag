def _hierarchical_rows(evalset: Path, corpus_path: Path, index: Any, depth: int) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    """Reproduce the full EV04 schema with raw-document duplicate collapse.

    ``corpus_maps`` is the frozen historical helper: it keeps the first source
    document for metadata/flags while allowing several raw documents per code.
    Retrieval remains raw BM25 over every document; ``collapse_hits`` applies
    the historical first-score-occurrence rule before any rank or metric.
    """

    eval_rows = hierarchical.read_csv(evalset)
    hierarchical.validate_eval(eval_rows)
    corpus_by_code, code_flags, _ = hierarchical.corpus_maps(read_jsonl(corpus_path), {}, {})
    cases: list[dict[str, Any]] = []
    candidates: list[dict[str, Any]] = []
    for eval_row in eval_rows:
        query = hierarchical.clean(eval_row.get(hierarchical.QUERY_COLUMN))
        expected = hierarchical.code8(eval_row.get(hierarchical.LABEL_COLUMN))
        raw_hits = retrieve(index, query, top_n=len(index.doc_ids))
        hits, collapse = hierarchical.collapse_hits(raw_hits, depth)
        rank = rank_of_true(hits, expected)
        top = hits[0] if hits else {}
        flags = code_flags.get(expected, {})
        row: dict[str, Any] = {
            "case_id": hierarchical.clean(eval_row.get("case_id")), "id_unico": hierarchical.clean(eval_row.get("id_unico")),
            "declaracion": hierarchical.clean(eval_row.get("DECLARACION")), "serie": hierarchical.clean(eval_row.get("SERIE")),
            "query": query, "nandina_ref": expected, "partida_ref": expected[:4], "sub_partida_ref": expected[:6], "clase_ref": expected[:2],
            "reference_code_in_corpus": expected in corpus_by_code, "reference_doc_id": hierarchical.clean(corpus_by_code.get(expected, {}).get("doc_id")),
            "rank_ref": rank, "position_bucket": hierarchical.position_bucket(rank),
            "coverage_class": "reference_code_absent_from_corpus" if expected not in corpus_by_code else (hierarchical.position_bucket(rank) if rank > 0 else f"present_not_recovered_top_{depth}"),
            "retrieved_count": len(hits), "raw_retrieved_count": collapse["raw_retrieved_count"], "raw_repeated_code_count": collapse["raw_repeated_code_count"],
            "effective_ranking_has_repeated_codes": int(collapse["effective_has_repeated_codes"]), "top1_code": hierarchical.clean(top.get("code")),
            "top1_doc_id": hierarchical.clean(corpus_by_code.get(hierarchical.clean(top.get("code")), {}).get("doc_id")) if top else "",
            "top1_score": top.get("score", "") if top else "", "reciprocal_rank": mrr_from_rank(rank), "method": hierarchical.METHOD,
            "flag_missing_parent_4d": bool(flags.get("missing_parent_4d", False)), "flag_missing_parent_hs6": bool(flags.get("missing_parent_hs6", False)),
            "flag_missing_both_parents": bool(flags.get("missing_both_parents", False)), "flag_duplicate_code_documents": bool(flags.get("duplicate_code_documents", False)),
            "flag_generic_or_short_leaf_description": bool(flags.get("generic_or_short_leaf_description", False)),
        }
        for k in hierarchical.K_VALUES:
            row[f"hit_top_{k}"] = int(acc_at_k(rank, k))
        for k in hierarchical.RECALL_K_VALUES:
            row[f"hit_recall_{k}"] = int(acc_at_k(rank, k))
        for k in hierarchical.HIERARCHICAL_K_VALUES:
            row[f"exact_at_{k}"] = int(acc_at_k(rank, k))
            row[f"hs6_at_{k}"] = hierarchical.family_hit(hits, expected, 6, k)
            row[f"hs4_at_{k}"] = hierarchical.family_hit(hits, expected, 4, k)
            row[f"chapter_at_{k}"] = hierarchical.family_hit(hits, expected, 2, k)
        row["hierarchical_evidence_class_at_100"] = hierarchical.evidence_class(row, 100)
        row["hierarchical_evidence_class_at_200"] = hierarchical.evidence_class(row, 200)
        cases.append(row)
        for hit in hits:
            code = hierarchical.clean(hit.get("code"))
            candidates.append({
                "case_id": row["case_id"], "id_unico": row["id_unico"], "nandina_ref": expected, "candidate_rank": int(hit["rank"]),
                "candidate_raw_rank": int(hit.get("raw_rank", hit["rank"])), "candidate_doc_id": hierarchical.clean(corpus_by_code.get(code, {}).get("doc_id")) or f"NANDINA_{code}",
                "candidate_code": code, "candidate_partida": code[:4], "candidate_sub_partida": code[:6], "candidate_clase": code[:2],
                "score": float(hit["score"]), "candidate_text": hierarchical.clean(hit.get("text"))[:240], "is_reference_code": int(code == expected), "method": hierarchical.METHOD,
            })
    return cases, candidates, hierarchical.metrics_from_cases(cases)


def evaluate_arm(arm: str, corpus_path: Path, index_path: Path, metadata_path: Path, output_dir: Path, *, evalset: Path = EVALSET, config_path: Path = CONFIG, root: Path = ROOT) -> dict[str, Any]:
    """Produce future case/aggregate results after the runner has authorized it."""

    require(not output_dir.exists(), f"Corrective evaluator refuses overwrite or resume: {_relative(output_dir, root)}")
    inputs = validate_dynamic_inputs(arm, corpus_path, index_path, metadata_path, config_path=config_path)
    evalset = (root / evalset).resolve() if not evalset.is_absolute() else evalset.resolve()
    require(evalset.is_file(), f"Frozen EVAL is missing: {_relative(evalset, root)}")
    depth = 100 if arm == "EV03" else 200
    if arm == "EV03":
        cases, candidates, metrics = _flat_rows(evalset, corpus_path, inputs["index"], depth)
        prefix = "normative_flat"
        case_fields = EV03_CASE_FIELDS
        candidate_fields = EV03_CANDIDATE_FIELDS
    else:
        cases, candidates, metrics = _hierarchical_rows(evalset, corpus_path, inputs["index"], depth)
        prefix = "normative_hierarchical"
        case_fields = EV04_CASE_FIELDS
        candidate_fields = EV04_CANDIDATE_FIELDS
    output_dir.mkdir(parents=True, exist_ok=False)
    ranking = output_dir / f"{prefix}_results.csv"
    summary = output_dir / f"{prefix}_case_summary.csv"
    metric_file = output_dir / f"{prefix}_metrics.json"
    _write_csv_new(ranking, _normalize_rows(candidates), candidate_fields)
    _write_csv_new(summary, _normalize_rows(cases), case_fields)
    payload = {"arm": arm, "dynamic_inputs": {key: value for key, value in inputs.items() if key not in {"metadata", "index"}}, "evalset": _relative(evalset, root), "evalset_sha256": sha256_file(evalset), "retrieval_depth": depth, "metrics": metrics, "outputs": {"ranking": _relative(ranking, root), "case_summary": _relative(summary, root)}}
    _write_json_new(metric_file, payload)
    return payload


def _csv_schema(path: Path) -> list[str]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.reader(handle)
        header = next(reader, None)
    require(header is not None, f"CSV has no deterministic header: {path}")
    return header


def compare_control_reproduction(
    expected_ranking: Path,
    actual_ranking: Path,
    expected_summary: Path,
    actual_summary: Path,
    expected_metrics: Mapping[str, Any],
    actual_metrics: Mapping[str, Any],
    *,
    expected_candidate_schema: Sequence[str] | None = None,
    expected_case_schema: Sequence[str] | None = None,
) -> dict[str, Any]:
    """Require exact effective ranking, case summary, and metric evidence.

    Runtime/platform/timestamp metadata are intentionally outside this strict
    comparison; all ranking, case-level, numerator, denominator, and value
    evidence remains in scope.
    """

    expected_candidate_schema = list(expected_candidate_schema or _csv_schema(expected_ranking))
    expected_case_schema = list(expected_case_schema or _csv_schema(expected_summary))
    require(_csv_schema(expected_ranking) == expected_candidate_schema, "Frozen control candidate schema drifted")
    require(_csv_schema(expected_summary) == expected_case_schema, "Frozen control case schema drifted")
    expected_rank = flat._read_csv(expected_ranking)
    actual_rank = flat._read_csv(actual_ranking)
    expected_cases = flat._read_csv(expected_summary)
    actual_cases = flat._read_csv(actual_summary)
    metrics_equal = expected_metrics == actual_metrics
    result = {
        "ranking_schema_exact": _csv_schema(actual_ranking) == expected_candidate_schema,
        "case_summary_schema_exact": _csv_schema(actual_summary) == expected_case_schema,
        "ranking_exact": expected_rank == actual_rank,
        "case_summary_exact": expected_cases == actual_cases,
        "metrics_exact": metrics_equal,
        "comparison_scope": "EFFECTIVE_FULL_RANKING_CASE_LEVEL_AND_METRICS_EXCLUDING_RUNTIME_TIMESTAMPS",
    }
    require(all(result[key] for key in ("ranking_schema_exact", "case_summary_schema_exact", "ranking_exact", "case_summary_exact", "metrics_exact")), "Mandatory control reproduction is not exact")
    return {**result, "status": "PASS"}


def reproduce_ev04_decision885_control(
    corpus_path: Path,
    index_path: Path,
    metadata_path: Path,
    output_dir: Path,
    *,
    frozen_ranking: Path,
    frozen_case_summary: Path,
    frozen_metrics: Mapping[str, Any],
    root: Path = ROOT,
) -> dict[str, Any]:
    """Run and cryptographically compare the mandatory EV04 Decision885 control.

    The caller must invoke this before materializing either corrected corpus.
    A mismatch raises ``ContractViolation`` through ``compare_control_reproduction``
    and therefore cannot be ignored by a later corrected-arm invocation.
    """

    result = evaluate_arm("EV04", corpus_path, index_path, metadata_path, output_dir, root=root)
    return compare_control_reproduction(
        frozen_ranking,
        output_dir / "normative_hierarchical_results.csv",
        frozen_case_summary,
        output_dir / "normative_hierarchical_case_summary.csv",
        frozen_metrics,
        result["metrics"],
        expected_candidate_schema=EV04_CANDIDATE_FIELDS,
        expected_case_schema=EV04_CASE_FIELDS,
    )


def ev04_corrected_execution_permitted(*, authorized: bool, reproduction_status: str) -> bool:
    """Keep the control-reproduction and authorization gates independently closed."""

    return authorized and reproduction_status == "PASS"


def _case_summary_by_id(rows: Sequence[Mapping[str, Any]], label: str) -> dict[str, dict[str, Any]]:
    by_case: dict[str, dict[str, Any]] = {}
    for row in rows:
        case_id = str(row.get("case_id", "")).strip()
        require(case_id, f"{label} case summary has a missing case_id")
        require(case_id not in by_case, f"{label} case summary has a duplicate case_id: {case_id}")
        nandina_ref = str(row.get("nandina_ref", "")).strip()
        require(nandina_ref, f"{label} case summary has a missing nandina_ref: {case_id}")
        by_case[case_id] = dict(row)
    require(by_case, f"{label} case summary is empty")
    return by_case


def _rank_value(value: Any, label: str) -> int:
    text = str(value).strip()
    require(text.isdigit(), f"{label} candidate_rank is malformed: {value!r}")
    rank = int(text)
    require(rank >= 1, f"{label} candidate_rank must begin at one")
    return rank


def _effective_ranking_by_case(
    rows: Sequence[Mapping[str, Any]],
    case_ids: set[str],
    label: str,
    *,
    require_unique_codes: bool,
) -> dict[str, tuple[str, ...]]:
    grouped: dict[str, list[tuple[int, str]]] = {case_id: [] for case_id in case_ids}
    for row in rows:
        case_id = str(row.get("case_id", "")).strip()
        require(case_id in grouped, f"{label} candidate ranking references an unknown case_id: {case_id!r}")
        code = str(row.get("candidate_code", "")).strip()
        require(code, f"{label} candidate ranking has a missing candidate_code: {case_id}")
        grouped[case_id].append((_rank_value(row.get("candidate_rank"), f"{label} {case_id}"), code))

    rankings: dict[str, tuple[str, ...]] = {}
    for case_id, ranked in grouped.items():
        require(ranked, f"{label} candidate ranking is missing case_id: {case_id}")
        ranked.sort(key=lambda item: item[0])
        ranks = [rank for rank, _ in ranked]
        require(ranks == list(range(1, len(ranks) + 1)), f"{label} candidate ranks are not an effective contiguous sequence: {case_id}")
        codes = tuple(code for _, code in ranked)
        if require_unique_codes:
            require(len(codes) == len(set(codes)), f"{label} effective candidate ranking contains duplicate codes: {case_id}")
        rankings[case_id] = codes
    return rankings


def _rank_of(codes: Sequence[str], code: str) -> int:
    try:
        return list(codes).index(code) + 1
    except ValueError:
        return 0


def produce_case_level_comparison(
    arm_name: str,
    original_cases: Sequence[Mapping[str, Any]],
    corrective_cases: Sequence[Mapping[str, Any]],
    original_candidates: Sequence[Mapping[str, Any]],
    corrective_candidates: Sequence[Mapping[str, Any]],
) -> list[dict[str, Any]]:
    """Build the frozen full-effective-ranking comparison for one BM25 arm."""

    contract = case_level_comparison_contract(arm_name)
    original_by_case = _case_summary_by_id(original_cases, f"{arm_name} original")
    corrective_by_case = _case_summary_by_id(corrective_cases, f"{arm_name} corrective")
    case_ids = set(original_by_case)
    require(case_ids == set(corrective_by_case), "Case-level comparison requires identical original and corrective case IDs")
    unique_codes = arm_name == "EV04"
    original_rankings = _effective_ranking_by_case(original_candidates, case_ids, f"{arm_name} original", require_unique_codes=unique_codes)
    corrective_rankings = _effective_ranking_by_case(corrective_candidates, case_ids, f"{arm_name} corrective", require_unique_codes=unique_codes)

    rows: list[dict[str, Any]] = []
    for case_id in sorted(case_ids):
        original_summary = original_by_case[case_id]
        corrective_summary = corrective_by_case[case_id]
        nandina_ref = str(original_summary["nandina_ref"]).strip()
        require(nandina_ref == str(corrective_summary["nandina_ref"]).strip(), f"Case reference changed during corrective comparison: {case_id}")
        original_codes = original_rankings[case_id]
        corrected_codes = corrective_rankings[case_id]
        original_rank_ref = _rank_of(original_codes, nandina_ref)
        corrected_rank_ref = _rank_of(corrected_codes, nandina_ref)
        row: dict[str, Any] = {
            "case_id": case_id,
            "nandina_ref": nandina_ref,
            "original_rank_ref": original_rank_ref,
            "corrected_rank_ref": corrected_rank_ref,
            "ranking_changed": original_codes != corrected_codes,
            "rank_convention": contract["rank_convention"],
        }
        for k in contract["k_values"]:
            row[f"original_hit_{k}"] = int(1 <= original_rank_ref <= k)
            row[f"corrected_hit_{k}"] = int(1 <= corrected_rank_ref <= k)
        for code in ("87044110", "87045110"):
            original_rank = _rank_of(original_codes, code)
            corrected_rank = _rank_of(corrected_codes, code)
            row[f"original_rank_{code}"] = original_rank
            row[f"corrected_rank_{code}"] = corrected_rank
            row[f"original_contains_{code}"] = original_rank > 0
            row[f"corrected_contains_{code}"] = corrected_rank > 0
        require(list(row) == contract["field_order"], f"{arm_name} case-level comparison schema drifted")
        rows.append(row)
    return rows


def _metric_table(metrics: Mapping[str, Any], label: str) -> list[dict[str, Any]]:
    table = metrics.get("metric_table")
    require(isinstance(table, list) and table, f"{label} metric_table is missing")
    normalized: list[dict[str, Any]] = []
    required = {"metric", "numerator", "denominator", "value"}
    for row in table:
        require(isinstance(row, Mapping) and set(row) == required, f"{label} metric_table row schema changed")
        metric = row.get("metric")
        require(isinstance(metric, str) and metric, f"{label} metric_table metric is malformed")
        for field in ("numerator", "denominator", "value"):
            value = row.get(field)
            require(isinstance(value, (int, float)) and not isinstance(value, bool), f"{label} metric_table {field} is not numeric: {metric}")
        normalized.append(dict(row))
    names = [str(row["metric"]) for row in normalized]
    require(len(names) == len(set(names)), f"{label} metric_table contains duplicate metrics")
    return normalized


def produce_aggregate_comparison(original_metrics: Mapping[str, Any], corrective_metrics: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Compare only the frozen metric tables with matched denominators."""

    original_table = _metric_table(original_metrics, "Original")
    corrected_table = _metric_table(corrective_metrics, "Corrective")
    original_names = [str(row["metric"]) for row in original_table]
    corrected_names = [str(row["metric"]) for row in corrected_table]
    require(corrected_names == original_names, "Corrective metric_table names or order changed")
    comparison: list[dict[str, Any]] = []
    for original, corrected in zip(original_table, corrected_table, strict=True):
        require(
            float(original["denominator"]) == float(corrected["denominator"]),
            f"Aggregate denominator mismatch: {original['metric']}",
        )
        comparison.append(
            {
                "metric": original["metric"],
                "original_numerator": original["numerator"],
                "corrected_numerator": corrected["numerator"],
                "denominator": original["denominator"],
                "original_value": original["value"],
                "corrected_value": corrected["value"],
                "absolute_delta": float(corrected["value"]) - float(original["value"]),
            }
        )
    return comparison


